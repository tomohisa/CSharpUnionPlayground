using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace CSharpUnionPlayground.Experimental.Generators;

[Generator]
public sealed class TaggedJsonGenerator : IIncrementalGenerator
{
    private const string Prefix = "CSharpUnionPlayground.Experimental.Json.";
    private static readonly DiagnosticDescriptor Invalid = new(
        "CUPJ001", "Unsupported experimental tagged union", "{0}",
        "PlaygroundTaggedJson", DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(c => c.AddSource("PlaygroundTaggedJsonAttributes.g.cs", SourceText.From("""
// <auto-generated/>
#nullable enable
namespace CSharpUnionPlayground.Experimental.Json
{
    [global::System.AttributeUsage(global::System.AttributeTargets.Struct)]
    internal sealed class PlaygroundTaggedUnionAttribute : global::System.Attribute
    {
        public string Discriminator { get; set; } = "$type";
    }
    [global::System.AttributeUsage(global::System.AttributeTargets.Struct, AllowMultiple = true)]
    internal sealed class PlaygroundUnionCaseAttribute : global::System.Attribute
    {
        public PlaygroundUnionCaseAttribute(global::System.Type caseType, string tag) { }
    }
}
""", Encoding.UTF8)));
        var unions = context.SyntaxProvider.ForAttributeWithMetadataName(
            Prefix + "PlaygroundTaggedUnionAttribute", (_, _) => true,
            (c, _) => (INamedTypeSymbol)c.TargetSymbol);
        context.RegisterSourceOutput(unions, Emit);
    }

    private static void Emit(SourceProductionContext context, INamedTypeSymbol union)
    {
        void Error(string message) => context.ReportDiagnostic(Diagnostic.Create(Invalid, union.Locations.FirstOrDefault(), message));
        if (union.ContainingType != null || union.TypeParameters.Length != 0 ||
            !union.DeclaringSyntaxReferences.Any(r => r.GetSyntax().GetType().Name == "UnionDeclarationSyntax"))
        {
            Error("Only top-level, non-generic C# unions are supported.");
            return;
        }
        var attr = union.GetAttributes().First(a => a.AttributeClass?.ToDisplayString() == Prefix + "PlaygroundTaggedUnionAttribute");
        var discriminator = attr.NamedArguments.FirstOrDefault(p => p.Key == "Discriminator").Value.Value as string ?? "$type";
        if (string.IsNullOrWhiteSpace(discriminator) || discriminator == "data")
        {
            Error("The discriminator must be nonempty and different from 'data'."); return;
        }
        var cases = new List<(ITypeSymbol Type, string Tag)>();
        foreach (var a in union.GetAttributes().Where(a => a.AttributeClass?.ToDisplayString() == Prefix + "PlaygroundUnionCaseAttribute"))
        {
            if (a.ConstructorArguments[0].Value is not ITypeSymbol type ||
                a.ConstructorArguments[1].Value is not string tag || string.IsNullOrWhiteSpace(tag))
            { Error("Each case requires a type and a nonempty tag."); return; }
            if (cases.Any(c => c.Tag == tag || SymbolEqualityComparer.Default.Equals(c.Type, type)))
            { Error("Case types and tags must be unique."); return; }
            cases.Add((type, tag));
        }
        // Case constructors are compiler-synthesized. Requiring an exact constructor
        // also rejects unrelated types without relying on union syntax internals.
        var constructors = union.InstanceConstructors.Where(c => c.Parameters.Length == 1).ToArray();
        if (cases.Count == 0 || cases.Any(c => !constructors.Any(k => SymbolEqualityComparer.Default.Equals(k.Parameters[0].Type, c.Type))) ||
            constructors.Any(k => !SymbolEqualityComparer.Default.Equals(k.Parameters[0].Type, union) && !cases.Any(c => SymbolEqualityComparer.Default.Equals(c.Type, k.Parameters[0].Type))))
        { Error("Register every union case exactly once; unrelated case types are not supported."); return; }

        string TypeName(ITypeSymbol t) => t.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        string Literal(string s) => SymbolDisplay.FormatLiteral(s, true);
        var full = TypeName(union);
        var name = union.Name + "PlaygroundJsonConverter";
        var ns = union.ContainingNamespace.IsGlobalNamespace ? null : union.ContainingNamespace.ToDisplayString();
        var b = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        if (ns != null) b.Append("namespace ").Append(ns).Append(" {\n");
        b.Append("public sealed class ").Append(name).Append(" : global::System.Text.Json.Serialization.JsonConverter<").Append(full).Append("> {\n");
        b.Append("public override ").Append(full).Append(" Read(ref global::System.Text.Json.Utf8JsonReader reader, global::System.Type typeToConvert, global::System.Text.Json.JsonSerializerOptions options) {\n")
         .Append("if (reader.TokenType == global::System.Text.Json.JsonTokenType.Null) return default;\n")
         .Append("using var doc = global::System.Text.Json.JsonDocument.ParseValue(ref reader);\nvar root = doc.RootElement;\n")
         .Append("if (root.ValueKind != global::System.Text.Json.JsonValueKind.Object) throw new global::System.Text.Json.JsonException(\"Expected a tagged union object.\");\n")
         .Append("global::System.Text.Json.JsonElement tag = default, data = default; bool hasTag = false, hasData = false;\n")
         .Append("foreach (var p in root.EnumerateObject()) {\n")
         .Append("if (p.NameEquals(").Append(Literal(discriminator)).Append(")) { if (hasTag) throw new global::System.Text.Json.JsonException(\"Duplicate discriminator.\"); hasTag = true; tag = p.Value; }\n")
         .Append("else if (p.NameEquals(\"data\")) { if (hasData) throw new global::System.Text.Json.JsonException(\"Duplicate data.\"); hasData = true; data = p.Value; }\n")
         .Append("else throw new global::System.Text.Json.JsonException(\"Unknown envelope property.\"); }\n")
         .Append("if (!hasTag || !hasData || tag.ValueKind != global::System.Text.Json.JsonValueKind.String || data.ValueKind == global::System.Text.Json.JsonValueKind.Null) throw new global::System.Text.Json.JsonException(\"Expected discriminator and non-null data.\");\n")
         .Append("switch (tag.GetString()) {\n");
        foreach (var c in cases)
            b.Append("case ").Append(Literal(c.Tag)).Append(": return new ").Append(full).Append("(global::System.Text.Json.JsonSerializer.Deserialize(data, (global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<")
             .Append(TypeName(c.Type)).Append(">)options.GetTypeInfo(typeof(").Append(TypeName(c.Type)).Append(")))!);\n");
        b.Append("default: throw new global::System.Text.Json.JsonException(\"Unknown union tag.\"); } }\n")
         .Append("public override void Write(global::System.Text.Json.Utf8JsonWriter writer, ").Append(full).Append(" value, global::System.Text.Json.JsonSerializerOptions options) {\n")
         .Append("if (value.Value is null) { writer.WriteNullValue(); return; }\nwriter.WriteStartObject();\nswitch (value.Value) {\n");
        foreach (var c in cases)
            b.Append("case ").Append(TypeName(c.Type)).Append(" item when item.GetType() == typeof(").Append(TypeName(c.Type)).Append("): writer.WriteString(").Append(Literal(discriminator)).Append(", ").Append(Literal(c.Tag))
             .Append("); writer.WritePropertyName(\"data\"); global::System.Text.Json.JsonSerializer.Serialize(writer, item, (global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<")
             .Append(TypeName(c.Type)).Append(">)options.GetTypeInfo(typeof(").Append(TypeName(c.Type)).Append("))); break;\n");
        b.Append("default: throw new global::System.Text.Json.JsonException(\"Unsupported union case.\"); } writer.WriteEndObject(); }\n}\n");
        if (ns != null) b.Append("}\n");
        context.AddSource((ns + "." + name) + ".g.cs", SourceText.From(b.ToString(), Encoding.UTF8));
    }
}
